/* Friendly Pay 13 — build. Static site, no framework: this script only CONCATENATES and MINIFIES what index.src.html already lists.
   usage:  cd tools && npm ci && node build.mjs          (writes ../index.html, ../js/app.js, ../css/app.css)
   - index.src.html  = the readable page: every script and style, one by one, in the order that matters (see architecture.md)
   - js/app.js       = those scripts, in the same order, one file, minified (names of top-level functions / constants are KEPT: they are shared globals)
   - css/app.css     = those style sheets, in the same order, one file, minified
   - js/vendor/*     (Reown AppKit, loaded on demand) and the Supabase client on the CDN stay separate.
   Nothing is rewritten: the bundle behaves like the separate files (same global scope, same order). */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const esbuild = require('esbuild');
const { transform } = require('lightningcss');
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = fs.readFileSync(path.join(ROOT, 'index.src.html'), 'utf8');
const local = re => [...src.matchAll(re)].map(m => m[1]).filter(u => !/^https?:/.test(u));
const jsFiles = local(/<script src="([^"]+)"[^>]*><\/script>/g).filter(u => !u.startsWith('js/vendor/'));
const cssFiles = local(/<link rel="stylesheet" href="([^"]+)">/g);
const read = f => fs.readFileSync(path.join(ROOT, f), 'utf8');

/* JS */
const jsIn = jsFiles.map(f => '/* ' + f + ' */\n' + read(f)).join('\n;\n');
const js = esbuild.transformSync(jsIn, { loader: 'js', minify: true, target: 'es2020', legalComments: 'none', charset: 'utf8' }).code;
fs.writeFileSync(path.join(ROOT, 'js/app.js'), js);
/* CSS */
const cssIn = cssFiles.map(f => '/* ' + f + ' */\n' + read(f).replace(/url\((\.\.\/assets\/)/g, 'url(../assets/')).join('\n');
const css = transform({ filename: 'app.css', code: Buffer.from(cssIn), minify: true }).code.toString();
fs.writeFileSync(path.join(ROOT, 'css/app.css'), css);
/* page: the same head and body, the scripts / styles replaced by the two bundles */
let html = src;
cssFiles.forEach((f, i) => { html = html.replace('<link rel="stylesheet" href="' + f + '">\n', i === 0 ? '<link rel="stylesheet" href="css/app.css">\n' : ''); });
jsFiles.forEach((f, i) => { html = html.replace(new RegExp('<script src="' + f.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '"[^>]*></script>\\n?'), i === 0 ? '<script src="js/app.js" defer></script>\n' : ''); });
html = html.replace('<!-- built -->', '');
fs.writeFileSync(path.join(ROOT, 'index.html'), html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- GENERATED by tools/build.mjs from index.src.html — edit index.src.html, then rebuild. -->'));
const kb = n => (n / 1024).toFixed(1) + ' KB', gz = b => zlib.brotliCompressSync(Buffer.from(b)).length;
console.log('js :', jsFiles.length, 'files', kb(jsIn.length), '->', kb(js.length), '(brotli', kb(gz(js)) + ')');
console.log('css:', cssFiles.length, 'files', kb(cssIn.length), '->', kb(css.length), '(brotli', kb(gz(css)) + ')');
